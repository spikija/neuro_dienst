extension AppLocalizationFormatting on AppLocalizations {
  String fill(String key, Map<String, Object> values) {
    var text = t(key);

    for (final entry in values.entries) {
      text = text.replaceAll('{${entry.key}}', entry.value.toString());
    }

    return text;
  }
}
